/**
 * A2A agent server backed by a real LLM (GitHub Models).
 *
 * The A2A protocol wiring (agent card, task lifecycle, streaming) is unchanged
 * from the spike. The only difference is the "brain" inside execute(): instead
 * of hardcoded logic, it calls a model via GitHub Models using your GitHub
 * token.
 *
 * Auth: set a GitHub token with the "models" permission before starting:
 *   export GITHUB_TOKEN=ghp_xxx   (or:  export GITHUB_TOKEN=$(gh auth token))
 *
 * Any A2A client (including a GitHub Copilot agent that speaks A2A) can:
 *   1. fetch the agent card at /.well-known/agent-card.json
 *   2. POST a message and stream back a Task with status updates + a result.
 */
import express from "express";
import { v4 as uuidv4 } from "uuid";
import type {
  AgentCard,
  Message,
  Task,
  TaskStatusUpdateEvent,
} from "@a2a-js/sdk";
import {
  type AgentExecutor,
  type ExecutionEventBus,
  type RequestContext,
  DefaultRequestHandler,
  InMemoryTaskStore,
} from "@a2a-js/sdk/server";
import {
  agentCardHandler,
  jsonRpcHandler,
  UserBuilder,
} from "@a2a-js/sdk/server/express";
import { AGENT_CARD_PATH, BASE_URL, PORT, textOf } from "../shared/config.js";

/** The capability description other agents discover. */
const agentCard: AgentCard = {
  protocolVersion: "0.3.0",
  name: "GitHub Models Chat Agent",
  description:
    "An A2A agent whose responses are generated by a large language model " +
    "served through GitHub Models. Send it any natural-language message.",
  url: BASE_URL,
  preferredTransport: "JSONRPC",
  version: "0.2.0",
  defaultInputModes: ["text/plain"],
  defaultOutputModes: ["text/plain"],
  capabilities: {
    streaming: true,
    pushNotifications: false,
    stateTransitionHistory: true,
  },
  skills: [
    {
      id: "chat",
      name: "Chat",
      description:
        "Answer questions, summarize, brainstorm, or hold a conversation. " +
        "Backed by an LLM via GitHub Models.",
      tags: ["chat", "llm", "github-models"],
      examples: [
        "Explain the A2A protocol in one sentence.",
        "Give me three names for a coffee shop.",
        "What is the capital of Japan?",
      ],
    },
  ],
};

// --- LLM backend: GitHub Models (OpenAI-compatible) -------------------------
const GITHUB_TOKEN = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;
const MODEL = process.env.GITHUB_MODELS_MODEL ?? "openai/gpt-4o-mini";
const MODELS_ENDPOINT =
  process.env.GITHUB_MODELS_ENDPOINT ?? "https://models.github.ai/inference";

const SYSTEM_PROMPT =
  "You are a concise, helpful assistant exposed over the A2A protocol. " +
  "Answer directly and keep replies short unless asked otherwise.";

/**
 * Core "business logic" of the agent — now a real LLM call.
 *
 * Sends the user's text to a model via GitHub Models and returns the reply.
 * Throws if the token is missing or the request fails; execute() turns that
 * into a 'failed' task so the client sees a clean error.
 */
async function askModel(prompt: string, signal?: AbortSignal): Promise<string> {
  if (!GITHUB_TOKEN) {
    throw new Error(
      "GITHUB_TOKEN is not set. Provide a GitHub token with the 'models' " +
        "permission, e.g. export GITHUB_TOKEN=$(gh auth token)",
    );
  }

  const response = await fetch(`${MODELS_ENDPOINT}/chat/completions`, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${GITHUB_TOKEN}`,
    },
    body: JSON.stringify({
      model: MODEL,
      messages: [
        { role: "system", content: SYSTEM_PROMPT },
        { role: "user", content: prompt },
      ],
    }),
    signal,
  });

  if (!response.ok) {
    const detail = await response.text();
    throw new Error(
      `GitHub Models request failed (${response.status}): ${detail}`,
    );
  }

  const data = (await response.json()) as {
    choices?: Array<{ message?: { content?: string } }>;
  };
  return data.choices?.[0]?.message?.content?.trim() ?? "(empty response)";
}

/**
 * The AgentExecutor is where the SDK hands us an incoming request and an event
 * bus to publish results on. We model the work as a Task so the client sees a
 * realistic lifecycle: submitted -> working -> completed.
 */
class ChatAgentExecutor implements AgentExecutor {
  private readonly cancelled = new Set<string>();

  async execute(
    requestContext: RequestContext,
    eventBus: ExecutionEventBus,
  ): Promise<void> {
    const userMessage = requestContext.userMessage;
    const taskId = requestContext.task?.id ?? requestContext.taskId ?? uuidv4();
    const contextId =
      userMessage.contextId ?? requestContext.contextId ?? uuidv4();

    // 1. Announce the task as submitted.
    const initialTask: Task = {
      kind: "task",
      id: taskId,
      contextId,
      status: { state: "submitted", timestamp: new Date().toISOString() },
      history: [userMessage],
      metadata: userMessage.metadata,
    };
    eventBus.publish(initialTask);

    // 2. Move to "working".
    const working: TaskStatusUpdateEvent = {
      kind: "status-update",
      taskId,
      contextId,
      status: { state: "working", timestamp: new Date().toISOString() },
      final: false,
    };
    eventBus.publish(working);

    if (this.cancelled.has(taskId)) {
      return;
    }

    // 3. Call the LLM. On failure, emit a 'failed' task instead of crashing.
    let result: string;
    try {
      result = await askModel(textOf(userMessage));
    } catch (err) {
      const failed: TaskStatusUpdateEvent = {
        kind: "status-update",
        taskId,
        contextId,
        status: {
          state: "failed",
          message: {
            kind: "message",
            role: "agent",
            messageId: uuidv4(),
            taskId,
            contextId,
            parts: [
              { kind: "text", text: `Model call failed: ${(err as Error).message}` },
            ],
          },
          timestamp: new Date().toISOString(),
        },
        final: true,
      };
      eventBus.publish(failed);
      eventBus.finished();
      return;
    }

    // 4. Emit the final agent message + completed status.
    const agentMessage: Message = {
      kind: "message",
      role: "agent",
      messageId: uuidv4(),
      taskId,
      contextId,
      parts: [{ kind: "text", text: result }],
    };

    const completed: TaskStatusUpdateEvent = {
      kind: "status-update",
      taskId,
      contextId,
      status: {
        state: "completed",
        message: agentMessage,
        timestamp: new Date().toISOString(),
      },
      final: true,
    };
    eventBus.publish(completed);
    eventBus.finished();
  }

  async cancelTask(
    taskId: string,
    _eventBus: ExecutionEventBus,
  ): Promise<void> {
    this.cancelled.add(taskId);
  }
}

function main(): void {
  const taskStore = new InMemoryTaskStore();
  const executor = new ChatAgentExecutor();
  const requestHandler = new DefaultRequestHandler(
    agentCard,
    taskStore,
    executor,
  );

  const app = express();
  app.disable("x-powered-by");
  app.use(express.json());
  app.use(
    AGENT_CARD_PATH,
    agentCardHandler({ agentCardProvider: requestHandler }),
  );
  app.use(
    jsonRpcHandler({
      requestHandler,
      userBuilder: UserBuilder.noAuthentication,
    }),
  );

  app.listen(PORT, "127.0.0.1", () => {
    console.log(`[agent] ${agentCard.name} listening on ${BASE_URL}`);
    console.log(`[agent] Model: ${MODEL} via ${MODELS_ENDPOINT}`);
    console.log(`[agent] Agent card: ${BASE_URL}/.well-known/agent-card.json`);
  });
}

main();
